# Protocol tests against the simulated printer in fake_printer.py.
#     python3 -m unittest discover -s tests -v
# Needs Python 3.8+ and the `openssl` command. Nothing touches a real printer.

import hashlib
import io
import os
import shutil
import sys
import tempfile
import time
import unittest
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "BambuLAN"))

import bambu_lan as bl  # noqa: E402
from fake_printer import CODE, SERIAL, FakePrinter, make_certs  # noqa: E402

GCODE = "; generated by Cura\nG28\n" + "G1 X10 Y10 E0.5\n" * 20000


class ProtocolTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.certs = tempfile.mkdtemp()
        cls._orig = (bl.CA_FILE, bl.MQTT_PORT, bl.FTP_PORT)
        bl.CA_FILE = make_certs(cls.certs)

    @classmethod
    def tearDownClass(cls):
        bl.CA_FILE, bl.MQTT_PORT, bl.FTP_PORT = cls._orig
        shutil.rmtree(cls.certs, ignore_errors=True)

    def setUp(self):
        self.printers = []

    def tearDown(self):
        for p in self.printers:
            p.stop()

    def printer(self, **kw):
        p = FakePrinter(self.certs, **kw)
        bl.MQTT_PORT, bl.FTP_PORT = p.mqtt_port, p.ftp_port
        self.printers.append(p)
        return p

    @staticmethod
    def cfg(**kw):
        c = {"ip": "127.0.0.1", "access_code": CODE, "serial": "", "insecure": False, "start": True,
             "filament": -1, "bed_levelling": True, "flow_cali": False, "timelapse": False, "bed_type": "auto"}
        c.update(kw)
        return c

    def assertBambuError(self, fn, *words):
        with self.assertRaises(bl.BambuError) as cm:
            fn()
        for w in words:
            self.assertIn(w, str(cm.exception))
        return str(cm.exception)

    # ---- connecting
    def test_serial_from_verified_certificate(self):
        self.printer()
        self.assertEqual(bl.detect_serial("127.0.0.1"), SERIAL)

    def test_connection_report(self):
        self.printer()
        serial, report = bl.test_connection(self.cfg())
        self.assertEqual(serial, SERIAL)
        for line in ("MQTT: logged in", "FTPS: logged in", "SD card: present", "verified against Bambu Lab CA"):
            self.assertIn(line, report)

    def test_wrong_access_code(self):
        self.printer()
        self.assertBambuError(lambda: bl.send_print(self.cfg(access_code="wrong"), GCODE, "x"), "access code")

    def test_wrong_serial_fails_certificate(self):
        self.printer()
        self.assertBambuError(lambda: bl.send_print(self.cfg(serial="01P00A999999999"), GCODE, "x"), "ertificate")

    def test_rogue_certificate_rejected(self):
        self.printer(cert="rogue")
        self.assertBambuError(lambda: bl.detect_serial("127.0.0.1"), "Skip certificate check")

    def test_insecure_mode(self):
        self.printer(cert="rogue")
        self.assertEqual(bl.detect_serial("127.0.0.1", verify=False), SERIAL)
        self.assertTrue(bl.send_print(self.cfg(insecure=True), GCODE, "x").startswith("Printing"))

    def test_nothing_listening(self):
        s = __import__("socket").socket()
        s.bind(("127.0.0.1", 0))
        bl.MQTT_PORT = s.getsockname()[1]
        s.close()
        self.assertBambuError(lambda: bl.detect_serial("127.0.0.1"), "refused")

    # ---- printing
    def test_full_print(self):
        p = self.printer()
        stages, progress = [], []
        result = bl.send_print(self.cfg(filament=2, timelapse=True), GCODE, "My Benchy v2 (final).stl",
                               lambda s, t: progress.append((s, t)), stages.append)
        self.assertTrue(result.startswith("Printing"), result)
        self.assertEqual(stages, ["Connecting", "Uploading", "Starting print"])
        self.assertIn("/My_Benchy_v2_final.gcode.3mf", p.files)
        z = zipfile.ZipFile(io.BytesIO(p.files["/My_Benchy_v2_final.gcode.3mf"]))
        self.assertEqual(z.read("Metadata/plate_1.gcode").decode(), GCODE)
        self.assertEqual(z.read("Metadata/plate_1.gcode.md5").decode(),
                         hashlib.md5(GCODE.encode()).hexdigest().upper())
        self.assertEqual(p.reused, [True], "FTPS data channel must reuse the TLS session")
        self.assertEqual(progress[-1][0], progress[-1][1])
        job = p.jobs()[0]
        self.assertEqual(job["param"], "Metadata/plate_1.gcode")
        self.assertTrue(job["use_ams"])
        self.assertEqual(job["ams_mapping"], [2])
        self.assertTrue(job["timelapse"])
        seq = [m[list(m)[0]]["sequence_id"] for _, m in p.requests]
        self.assertEqual(len(seq), len(set(seq)), "sequence ids must be unique")

    def test_busy_printer_refused_before_upload(self):
        p = self.printer(state="RUNNING")
        self.assertBambuError(lambda: bl.send_print(self.cfg(), GCODE, "x"), "busy")
        self.assertFalse(p.files)

    def test_missing_sd_card(self):
        self.printer(sdcard=False)
        self.assertBambuError(lambda: bl.send_print(self.cfg(), GCODE, "x"), "SD card")

    def test_printer_without_sdcard_field(self):
        self.printer(sdcard=None)
        self.assertTrue(bl.send_print(self.cfg(), GCODE, "x").startswith("Printing"))

    def test_refusal_reason_shown(self):
        self.printer(refuse_job=True)
        self.assertBambuError(lambda: bl.send_print(self.cfg(), GCODE, "x"), "file not found")

    def test_upload_only(self):
        p = self.printer()
        result = bl.send_print(self.cfg(start=False), GCODE, "upload only")
        self.assertIn("Uploaded", result)
        self.assertIn("/upload_only.gcode.3mf", p.files)
        self.assertFalse(p.requests)

    # ---- models and firmware
    def test_old_a1_firmware(self):
        p = self.printer(model="A1_old")
        _, report = bl.test_connection(self.cfg())
        self.assertIn("Model: A1, firmware 01.04.02.00", report)
        self.assertIn("no Developer Mode needed", report)
        self.assertTrue(bl.send_print(self.cfg(), GCODE, "a1 job").startswith("Printing"))
        self.assertEqual([j["url"] for j in p.jobs()], ["file:///sdcard/a1_job.gcode.3mf"])
        self.assertFalse(p.jobs()[0]["use_ams"])

    def test_new_a1_firmware(self):
        self.printer(model="A1_new")
        _, report = bl.test_connection(self.cfg())
        self.assertIn("Developer Mode must be on", report)

    def test_h2d_uses_ftp_url(self):
        p = self.printer(model="H2D")
        self.assertTrue(bl.send_print(self.cfg(), GCODE, "h2d").startswith("Printing"))
        self.assertEqual([j["url"] for j in p.jobs()], ["ftp:///h2d.gcode.3mf"])

    def test_unknown_model_falls_back(self):
        p = self.printer(model="H2D")
        original = bl.MiniMQTT.version
        bl.MiniMQTT.version = lambda self, seconds=5: ("", "")
        try:
            self.assertTrue(bl.send_print(self.cfg(), GCODE, "fallback").startswith("Printing"))
        finally:
            bl.MiniMQTT.version = original
        self.assertEqual([j["url"][:7] for j in p.jobs()], ["file://", "ftp:///"])

    def test_no_confirmation_is_a_soft_warning(self):
        self.printer(never_confirm=True)
        start = time.time()
        result = bl.send_print(self.cfg(), GCODE, "x")
        self.assertIn("hasn't confirmed", result)
        self.assertLess(time.time() - start, 40)

    # ---- helpers
    def test_ssdp_parsing(self):
        info = bl.parse_ssdp("NOTIFY * HTTP/1.1\r\nHOST: 239.255.255.250:1900\r\nLocation: 192.168.1.77\r\n"
                             "NT: urn:bambulab-com:device:3dprinter:1\r\nUSN: 01S00C123456789\r\n"
                             "DevModel.bambu.com: C11\r\nDevName.bambu.com: Garage P1S\r\n\r\n", "192.168.1.77")
        self.assertEqual(info, {"ip": "192.168.1.77", "serial": "01S00C123456789", "model": "C11", "name": "Garage P1S"})
        self.assertIsNone(bl.parse_ssdp("NOTIFY * HTTP/1.1\r\nNT: upnp:rootdevice\r\n\r\n", "1.2.3.4"))

    def test_discover_returns_without_printers(self):
        start = time.time()
        bl.discover(1)
        self.assertLess(time.time() - start, 3)

    def test_safe_filenames(self):
        self.assertEqual(bl.safe_filename(""), "cura_print.gcode.3mf")
        self.assertEqual(bl.safe_filename("CE3_über part.gcode"), "CE3_ber_part.gcode.3mf")
        self.assertEqual(bl.safe_filename("../../etc/passwd"), "etc_passwd.gcode.3mf")

    def test_firmware_rules(self):
        self.assertLess(bl._ver("01.04.02.00"), bl._ver("01.05.00.00"))
        self.assertIn("no Developer Mode", bl.firmware_note("A1", "01.04.02.00"))
        self.assertIn("must be on", bl.firmware_note("P1S", "01.08.02.00"))
        self.assertEqual(bl.firmware_note("", ""), "")
        self.assertEqual(bl.print_urls("A1", "f")[0], "file:///sdcard/f")
        self.assertEqual(bl.print_urls("H2D", "f")[0], "ftp:///f")


if __name__ == "__main__":
    unittest.main()
